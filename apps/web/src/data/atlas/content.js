export const cities = definitions.map(([id,name,tagline,keywords,intro,rows], index) => ({ id,name,tagline,keywords: keywords.split(' / '),intro,order:index+1, image:null, imageCredit:null,
  items: rows.trim().split('\n').map((row,i) => {
    const [slug,title,tags,description,details] = row.split('|')
    const observations = details.split('；')
    const category = categories[Math.floor(i/2)]
    const sourceKeys = ['heritage']
    if (i < 2 || ['huaian','suzhou'].includes(id)) sourceKeys.push(id)
    if (tags.includes('canal')) sourceKeys.push('canal')
    if (id === 'suzhou' && i >=4 && i <=5) sourceKeys.push('gardens')
    return { id:`${id}-${slug}`,cityId:id,title,category,themes:tags.split(','),summary:description.split('。')[0]+'。',
      body:[description, `细读这项文化，可以从三个角度开始：${observations.join('；')}。这些观察线索适合结合实物、展陈或现场演出使用，在细节之间建立自己的理解。`],
      observations, image:null, imageCredit:null, sources:[...new Set(sourceKeys)].map(key => references[key]) }
  })
}))
export const items = cities.flatMap(city => city.items)
export function themeCounts(theme) { return Object.fromEntries(cities.map(city => [city.id, city.items.filter(item => theme === 'all' || item.themes.includes(theme)).length])) }
export function relatedItems(item) {
  return items.filter(other => other.id !== item.id && other.themes.some(theme => item.themes.includes(theme)))
    .sort((a,b) => Number(a.cityId===item.cityId)-Number(b.cityId===item.cityId)).slice(0,3)
}
