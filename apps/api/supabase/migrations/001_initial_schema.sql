create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'profiles','categories','cities','heritage','traditional_arts','celebrities',
    'news','user_works','comments','user_collections'
  ] loop
    execute format('drop trigger if exists set_updated_at on public.%I', table_name);
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', table_name);
  end loop;
end;
$$;

create or replace function public.increment_counter(table_name text, row_id bigint, column_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if table_name not in ('heritage','traditional_arts','celebrities','news','user_works','comments') then
    raise exception 'invalid table';
  end if;
  if column_name not in ('view_count','like_count','collect_count','comment_count') then
    raise exception 'invalid column';
  end if;
  execute format('update public.%I set %I = %I + 1 where id = $1 and deleted = false', table_name, column_name, column_name)
    using row_id;
end;
$$;

revoke all on function public.increment_counter(text, bigint, text) from public;
grant execute on function public.increment_counter(text, bigint, text) to service_role;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'profiles','categories','cities','heritage','traditional_arts','celebrities',
    'news','user_works','comments','user_collections','search_history'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end;
$$;

