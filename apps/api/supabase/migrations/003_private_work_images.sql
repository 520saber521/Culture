create or replace function public.toggle_like(p_user_id bigint, p_type text, p_target_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  table_name text;
  exists_row boolean;
  removed bigint;
begin
  table_name := case p_type
    when 'heritage' then 'heritage'
    when 'work' then 'user_works'
    when 'comment' then 'comments'
    else null end;
  if table_name is null or p_target_id < 1 then raise exception 'invalid like target'; end if;
  execute format('select exists(select 1 from public.%I where id = $1 and status = 1 and deleted = false%s)',
    table_name, case when p_type = 'work' then ' and is_public = 1' else '' end)
    into exists_row using p_target_id;
  if not exists_row then raise exception 'like target not found'; end if;

  delete from public.user_likes
  where user_id = p_user_id and target_type = p_type and target_id = p_target_id
  returning id into removed;
  if removed is not null then
    execute format('update public.%I set like_count = greatest(0, like_count - 1) where id = $1', table_name) using p_target_id;
    return false;
  end if;
  insert into public.user_likes(user_id, target_type, target_id) values (p_user_id, p_type, p_target_id);
  execute format('update public.%I set like_count = like_count + 1 where id = $1', table_name) using p_target_id;
  return true;
end;
$$;

