create or replace function public.toggle_collection(p_user_id bigint, p_type text, p_target_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  table_name text;
  collection_id bigint;
  was_deleted boolean;
  target_exists boolean;
  collected boolean;
begin
  table_name := case p_type
    when 'heritage' then 'heritage' when 'art' then 'traditional_arts'
    when 'celebrity' then 'celebrities' when 'news' then 'news'
    when 'work' then 'user_works' else null end;
  if table_name is null or p_target_id < 1 then raise exception 'invalid collection target'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':' || p_type || ':' || p_target_id::text, 0));
  execute format('select exists(select 1 from public.%I where id = $1 and status = 1 and deleted = false%s)',
    table_name, case when p_type = 'work' then ' and is_public = 1' else '' end)
    into target_exists using p_target_id;
  if not target_exists then raise exception 'collection target not found'; end if;
  select id, deleted into collection_id, was_deleted from public.user_collections
  where user_id = p_user_id and target_type = p_type and target_id = p_target_id;
  if collection_id is null then
    insert into public.user_collections(user_id, target_type, target_id)
    values (p_user_id, p_type, p_target_id);
    collected := true;
  else
    collected := was_deleted;
    update public.user_collections set deleted = not was_deleted where id = collection_id;
  end if;
  execute format('update public.%I set collect_count = greatest(0, collect_count + $2) where id = $1', table_name)
    using p_target_id, case when collected then 1 else -1 end;
  return collected;
end;
$$;
revoke all on function public.toggle_collection(bigint, text, bigint) from public;
grant execute on function public.toggle_collection(bigint, text, bigint) to service_role;

create or replace function public.sync_comment_count()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  table_name text;
  change_count integer;
begin
  table_name := case new.target_type
    when 'heritage' then 'heritage' when 'art' then 'traditional_arts'
    when 'celebrity' then 'celebrities' when 'news' then 'news'
    when 'work' then 'user_works' else null end;
  if table_name is null then return new; end if;
  change_count := case when new.deleted = false and new.status = 1 then 1 else 0 end;
  if tg_op = 'UPDATE' then
    change_count := change_count - case when old.deleted = false and old.status = 1 then 1 else 0 end;
  end if;
  if change_count <> 0 then
    execute format('update public.%I set comment_count = greatest(0, comment_count + $2) where id = $1', table_name)
      using new.target_id, change_count;
  end if;
  return new;
end;
$$;
