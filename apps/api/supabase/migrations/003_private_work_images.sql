create or replace function public.get_operational_metrics()
returns jsonb
language sql stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'searchRequests', count(*) filter (where event_type = 'search'),
    'searchWithResults', count(*) filter (where event_type = 'search' and succeeded),
    'workSaveAttempts', count(*) filter (where event_type = 'work_save'),
    'workSaveSucceeded', count(*) filter (where event_type = 'work_save' and succeeded)
  )
  from public.metric_events
  where created_at >= now() - interval '7 days';
$$;
revoke all on function public.get_operational_metrics() from public;
grant execute on function public.get_operational_metrics() to service_role;

create or replace function public.reserve_ai_generation(p_user_id bigint, p_daily_limit integer)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  used_count integer;
  new_id bigint;
begin
  perform pg_advisory_xact_lock(p_user_id);
  select count(*) into used_count from public.ai_generations
  where user_id = p_user_id and created_at >= date_trunc('day', now() at time zone 'Asia/Shanghai') at time zone 'Asia/Shanghai'
    and status in ('pending','succeeded');
  if used_count >= p_daily_limit then raise exception 'daily image generation limit reached'; end if;
  insert into public.ai_generations(user_id) values (p_user_id) returning id into new_id;
  return new_id;
end;
$$;
revoke all on function public.reserve_ai_generation(bigint, integer) from public;
grant execute on function public.reserve_ai_generation(bigint, integer) to service_role;
